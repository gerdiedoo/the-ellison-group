import type { Listing } from '@/lib/types';
// Explicit public DTO: MLS raw payloads and future internal columns stay server-side.
export function publicListing(l: Listing): Listing {
  return {
    id: l.id,
    created_at: l.created_at,
    updated_at: l.updated_at,
    mls_id: l.mls_id,
    slug: l.slug,
    status: l.status,
    publication_status: l.publication_status,
    listing_kind: l.listing_kind,
    title: l.title,
    mls_id_locked: l.mls_id_locked,
    lead_capture_required: l.lead_capture_required,
    list_price: l.list_price,
    sold_price: l.sold_price,
    sold_date: l.sold_date,
    property_type: l.property_type,
    beds: l.beds,
    baths_full: l.baths_full,
    baths_half: l.baths_half,
    living_sqft: l.living_sqft,
    lot_acres: l.lot_acres,
    year_built: l.year_built,
    stories: l.stories,
    address_line: l.address_line,
    city: l.city,
    state: l.state,
    zip: l.zip,
    neighborhood_id: l.neighborhood_id,
    lat: l.lat,
    lng: l.lng,
    description: l.description,
    listing_agent_id: l.listing_agent_id,
    courtesy_of: l.courtesy_of,
    is_featured: l.is_featured,
    featured_rank: l.featured_rank,
    hidden: l.hidden,
    synced_at: l.synced_at,
    raw: {
      property_tax: l.raw?.property_tax ?? 0,
      demo: l.raw?.demo === true,
      pool: l.raw?.pool === true,
      garage: Number(l.raw?.garage) || 0,
      hoa: Number(l.raw?.hoa) || 0,
      architecture: typeof l.raw?.architecture === 'string' ? l.raw.architecture : '',
    },
    listing_photos: l.listing_photos
      .slice()
      .sort((a, b) => a.sort_order - b.sort_order)
      .map(({ id, listing_id, url, caption, sort_order, width, height, blurhash }) => ({
        id,
        listing_id,
        url,
        caption,
        sort_order,
        width,
        height,
        blurhash,
      })),
    listing_features: l.listing_features.map(({ id, listing_id, group, label, value }) => ({
      id,
      listing_id,
      group,
      label,
      value,
    })),
  };
}
